package com.deadlands.registry;

import com.deadlands.block.AxisDecorBlock;
import com.deadlands.block.DecorKind;
import com.deadlands.block.FacingDecorBlock;
import com.deadlands.block.LampHeadBlock;
import com.deadlands.block.PostDecorBlock;
import com.deadlands.block.PowerGeneratorBlock;
import java.util.EnumMap;
import java.util.Map;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockBehaviour;

/**
 * Furniture and roadside fixtures (one block per {@link DecorKind}). Models, textures, blockstates,
 * loot tables, names and mining tags are generated by tools/assetgen/gen_decor.py.
 */
public final class DLDecor {
	private static final Map<DecorKind, Block> BLOCKS = new EnumMap<>(DecorKind.class);

	static {
		for (DecorKind kind : DecorKind.values()) {
			DecorKind.Material material = kind.material();
			BlockBehaviour.Properties properties = BlockBehaviour.Properties.of()
				.mapColor(material.mapColor)
				.strength(material.hardness, material.hardness * 2.0F)
				.sound(material.sound)
				.noOcclusion()
				.isSuffocating(Blocks::never)
				.isViewBlocking(Blocks::never);
			if (material.needsTool) {
				properties = properties.requiresCorrectToolForDrops();
			}
			Block block = switch (kind.placement()) {
				case FACING -> DLBlocks.register(kind.id(), p -> new FacingDecorBlock(kind, p), properties, kind.tab());
				case POST -> DLBlocks.register(kind.id(), p -> new PostDecorBlock(kind, p), properties, kind.tab());
				case AXIS -> DLBlocks.register(kind.id(), p -> new AxisDecorBlock(kind, p), properties, kind.tab());
				case LAMP -> DLBlocks.register(kind.id(), p -> new LampHeadBlock(kind, p),
					properties.randomTicks().lightLevel(state -> state.getValue(LampHeadBlock.LIT) ? 14 : 0), kind.tab());
				case GENERATOR -> DLBlocks.register(kind.id(), p -> new PowerGeneratorBlock(kind, p),
					properties.lightLevel(state -> state.getValue(PowerGeneratorBlock.RUNNING) ? 6 : 0), kind.tab());
				case PUMP -> DLBlocks.register(kind.id(), p -> new com.deadlands.block.FuelPumpBlock(kind, p), properties, kind.tab());
				case WORKBENCH -> DLBlocks.register(kind.id(), p -> new com.deadlands.block.WorkbenchBlock(kind, p), properties, kind.tab());
			};
			BLOCKS.put(kind, block);
		}
	}

	private DLDecor() {
	}

	public static Block get(DecorKind kind) {
		return BLOCKS.get(kind);
	}

	public static void init() {
		// Class loading registers everything above.
	}
}
