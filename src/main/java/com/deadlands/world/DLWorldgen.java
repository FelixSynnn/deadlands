import net.minecraft.world.level.levelgen.structure.StructureType;
import net.minecraft.world.level.levelgen.structure.pieces.StructurePieceType;

/**
 * World generation types implemented in code. The biomes, configured and placed features,
 * structures and structure sets that use them are data (data/deadlands/worldgen, generated by
 * tools/assetgen/gen_world.py and gen_towns.py).
 */
public final class DLWorldgen {
	public static final Feature<NoneFeatureConfiguration> SURFACE_COVER = feature("surface_cover", new SurfaceCoverFeature());
	public static final Feature<NoneFeatureConfiguration> ROAD_NETWORK = feature("road_network", new RoadFeature());
	public static final Feature<NoneFeatureConfiguration> RAIL_NETWORK = feature("rail_network", new RailFeature());

	public static final StructurePieceType TOWN_STREET = piece("town_street", (StructurePieceType.ContextlessType) TownStreetPiece::new);
	public static final StructurePieceType TOWN_GATE = piece("town_gate", (StructurePieceType.ContextlessType) TownGatePiece::new);
	public static final StructurePieceType TOWN_BUILDING = piece("town_building", (StructurePieceType.StructureTemplateType) TownBuildingPiece::new);
	public static final StructurePieceType TOWN_CROSSING = piece("town_crossing", (StructurePieceType.ContextlessType) TownCrossingPiece::new);
	public static final StructureType<TownStructure> TOWN = Registry.register(BuiltInRegistries.STRUCTURE_TYPE, Deadlands.id("town"), () -> TownStructure.CODEC);

	/** The placed road feature (data/deadlands/worldgen/placed_feature/road_network.json). */
	public static final ResourceKey<PlacedFeature> ROAD_NETWORK_PLACED = ResourceKey.create(Registries.PLACED_FEATURE, Deadlands.id("road_network"));
	/** The placed railway feature (data/deadlands/worldgen/placed_feature/rail_network.json). */
	public static final ResourceKey<PlacedFeature> RAIL_NETWORK_PLACED = ResourceKey.create(Registries.PLACED_FEATURE, Deadlands.id("rail_network"));

	private DLWorldgen() {
	}

	private static <C extends FeatureConfiguration, F extends Feature<C>> F feature(String name, F feature) {
		return Registry.register(BuiltInRegistries.FEATURE, Deadlands.id(name), feature);
	}

	private static StructurePieceType piece(String name, StructurePieceType type) {
		return Registry.register(BuiltInRegistries.STRUCTURE_PIECE, Deadlands.id(name), type);
	}

	public static void init() {
		// Roads cross every overworld biome, vanilla ones included. Appended last in its step, so it
		// paints over the surface cover and never upsets the feature order (see docs/ARCHITECTURE.md).
		// Railways go first, so a road crossing a line overwrites it (a level crossing).
		BiomeModifications.addFeature(BiomeSelectors.foundInOverworld(), GenerationStep.Decoration.LOCAL_MODIFICATIONS, RAIL_NETWORK_PLACED);
		BiomeModifications.addFeature(BiomeSelectors.foundInOverworld(), GenerationStep.Decoration.LOCAL_MODIFICATIONS, ROAD_NETWORK_PLACED);
		// The vanilla biomes DEADLANDS keeps (oceans, rivers, beaches, peaks) lose their bright blue:
		// murky water and the same drab sky and haze as the DEADLANDS biomes around them.
		BiomeModifications.create(Deadlands.id("muted_vanilla_biomes")).add(ModificationPhase.POST_PROCESSING,
			context -> ConfigManager.get().world.deadlandsBiomes && BiomeSelectors.foundInOverworld().test(context)
				&& !context.getBiomeKey().identifier().getNamespace().equals(Deadlands.MOD_ID),
			(selection, modification) -> {
				modification.getEffects().setWaterColor(0xFF3E4A48);
				modification.getAttributes().set(EnvironmentAttributes.WATER_FOG_COLOR, 0xFF1A2322);
				modification.getAttributes().set(EnvironmentAttributes.FOG_COLOR, 0xFF9A9E9A);
				modification.getAttributes().set(EnvironmentAttributes.SKY_COLOR, 0xFF8C959A);
			});
		// Town sites and road geometry are cached per world; drop them when the server stops.
		ServerLifecycleEvents.SERVER_STOPPED.register(server -> {
			RoadNetwork.clearCaches();
			RailNetwork.clearCaches();
			TownSites.clearCaches();
		});
	}
}
