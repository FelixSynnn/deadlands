"""The story (Milestone 8): the lore catalogue as Java source (LoreEntries.java) and its English text,
and (in story_assets.py) the quest, radio and ending text, items, blocks, sites and sounds.

Lore lives in lore_data.py. Each entry becomes a LoreEntry in
src/main/java/com/deadlands/story/LoreEntries.java and two strings: lore.deadlands.<id>.title and
lore.deadlands.<id>.body.
"""
from __future__ import annotations

import dl_data as D
import dl_noise as N
import lore_data

NS = D.NS
JAVA = N.ROOT / "src" / "main" / "java" / "com" / "deadlands" / "story" / "LoreEntries.java"
CATEGORY_NAMES = {"research": "Harley's Research", "character": "Character Journals", "military": "Military Reports", "medical": "Medical Records",
                  "government": "Government Documents", "newspaper": "Newspapers", "radio": "Radio Transcripts", "missing": "Missing Persons",
                  "journal": "Personal Journals"}


def form(entry) -> str:
    if entry["title"].startswith("Photograph"):
        return "photo"
    return {"radio": "tape", "newspaper": "newspaper", "journal": "journal", "character": "journal"}.get(entry["category"], "document")


def java_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lore() -> int:
    rows = []
    for e in lore_data.ENTRIES:
        places = ", ".join(java_string(p) for p in e["places"])
        rows.append(f"\t\tnew LoreEntry({java_string(e['id'])}, LoreCategory.{e['category'].upper()}, List.of({places}), "
                    f"{java_string(e['series'])}, {e['part']}, {java_string(form(e))})")
    src = """package com.deadlands.story;

import java.util.List;

/**
 * GENERATED by tools/assetgen/gen_story.py from lore_data.py - do not edit; change the lore there and rerun it.
 *
 * <p>Every lore entry in the game. Text: {@code lore.deadlands.<id>.title} and {@code .body}.
 */
public final class LoreEntries {
	public static final List<LoreEntry> ALL = List.of(
""" + ",\n".join(rows) + """
	);

	private LoreEntries() {
	}
}
"""
    JAVA.write_text(src, encoding="utf-8")
    lang = {}
    for e in lore_data.ENTRIES:
        lang[f"lore.{NS}.{e['id']}.title"] = e["title"]
        lang[f"lore.{NS}.{e['id']}.body"] = e["body"]
    for cat, name in CATEGORY_NAMES.items():
        lang[f"lore.{NS}.category.{cat}"] = name
    D.merge_lang(lang)
    return len(lore_data.ENTRIES)


def build() -> int:
    count = lore()
    try:
        import story_assets
        story_assets.build()
    except ModuleNotFoundError as missing:
        if missing.name != "story_assets":
            raise
    return count


if __name__ == "__main__":
    print(build(), "lore entries written")
