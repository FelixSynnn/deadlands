"""Deterministic noise and image helpers shared by every DEADLANDS asset generator.

Everything here is seeded: the same seed always produces the same pixels, so assets
can be regenerated byte-for-byte and tweaked by editing a generator, never by hand.
Spectral noise is periodic, which makes it tile seamlessly (needed for block textures
and nine-slice GUI sprites whose centre and edges are repeated by the engine).
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage
from scipy.spatial import cKDTree

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "src" / "main" / "resources" / "assets" / "deadlands"


# ----------------------------------------------------------------------------- basics

def rng(seed: int) -> np.random.Generator:
    return np.random.default_rng(seed)


def normalize(a: np.ndarray) -> np.ndarray:
    lo, hi = float(a.min()), float(a.max())
    return (a - lo) / (hi - lo + 1e-12)


def smoothstep(e0: float, e1: float, x: np.ndarray) -> np.ndarray:
    t = np.clip((x - e0) / (e1 - e0 + 1e-12), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def hex_rgb(h: str) -> tuple[float, float, float]:
    h = h.lstrip("#")
    return tuple(float(int(h[i:i + 2], 16)) for i in (0, 2, 4))  # type: ignore[return-value]


def ramp(t: np.ndarray, stops: list[tuple[float, str]]) -> np.ndarray:
    """Map a 0..1 field through colour stops [(pos, '#rrggbb'), ...] -> HxWx3 float (0..255)."""
    t = np.clip(t, 0.0, 1.0)
    pos = np.array([s[0] for s in stops], dtype=float)
    cols = np.array([hex_rgb(s[1]) for s in stops], dtype=float)
    out = np.empty(t.shape + (3,), dtype=float)
    for c in range(3):
        out[..., c] = np.interp(t, pos, cols[:, c])
    return out


def solid(h: int, w: int, colour: str) -> np.ndarray:
    out = np.empty((h, w, 3), dtype=float)
    out[...] = hex_rgb(colour)
    return out


def lerp(a: np.ndarray, b: np.ndarray, t: np.ndarray | float) -> np.ndarray:
    if isinstance(t, np.ndarray) and t.ndim == 2 and a.ndim == 3:
        t = t[..., None]
    return a + (b - a) * t


# ----------------------------------------------------------------------------- noise

def spectral(h: int, w: int, beta: float = 2.0, seed: int = 0,
             fmin: float = 0.0, fmax: float | None = None,
             aniso: tuple[float, float] = (1.0, 1.0)) -> np.ndarray:
    """Periodic fractal noise by spectral synthesis, normalised to 0..1.

    beta ~1 gives fine grit, ~2 cloudy blotches, ~3 smooth rolling shapes.
    aniso stretches features: (1, 6) makes long horizontal streaks (brushed metal).
    """
    r = rng(seed)
    fy = np.fft.fftfreq(h)[:, None] * aniso[0]
    fx = np.fft.fftfreq(w)[None, :] * aniso[1]
    f = np.sqrt(fx * fx + fy * fy)
    f[0, 0] = 1.0
    amp = f ** (-beta / 2.0)
    amp[0, 0] = 0.0
    if fmin > 0.0:
        amp[f < fmin] = 0.0
    if fmax is not None:
        amp[f > fmax] = 0.0
    phase = r.uniform(0.0, 2.0 * np.pi, (h, w))
    field = np.real(np.fft.ifft2(amp * np.exp(1j * phase)))
    return normalize(field)


def worley(h: int, w: int, points: int, seed: int = 0, tileable: bool = True,
           k: int = 1) -> np.ndarray:
    """Cellular (Worley) distance field. Returns F1 (k=1) or stacked F1..Fk, scaled 0..1-ish."""
    r = rng(seed)
    pts = r.uniform(0.0, 1.0, (points, 2)) * np.array([h, w], dtype=float)
    tree = cKDTree(pts, boxsize=[h, w]) if tileable else cKDTree(pts)
    yy, xx = np.mgrid[0:h, 0:w]
    q = np.stack([yy.ravel() + 0.5, xx.ravel() + 0.5], axis=-1)
    d, _ = tree.query(q, k=k)
    cell = np.sqrt(h * w / points)
    if k == 1:
        return (d / cell).reshape(h, w)
    return (d / cell).reshape(h, w, k)


def warp(field: np.ndarray, dx: np.ndarray, dy: np.ndarray, wrap: bool = True) -> np.ndarray:
    h, w = field.shape
    yy, xx = np.mgrid[0:h, 0:w].astype(float)
    return ndimage.map_coordinates(field, [yy + dy, xx + dx], order=1,
                                   mode="grid-wrap" if wrap else "nearest")


def blur(a: np.ndarray, sigma, wrap: bool = True) -> np.ndarray:
    return ndimage.gaussian_filter(a, sigma, mode="wrap" if wrap else "nearest")


def shade(height: np.ndarray, strength: float = 2.0,
          light: tuple[float, float, float] = (-1.0, -1.0, 1.6), wrap: bool = True) -> np.ndarray:
    """Lambert shading of a height field (light from top-left by default). Returns ~0..1."""
    mode = "wrap" if wrap else "nearest"
    gy = ndimage.sobel(height, axis=0, mode=mode)
    gx = ndimage.sobel(height, axis=1, mode=mode)
    nx, ny, nz = -gx * strength, -gy * strength, np.ones_like(height)
    n = np.sqrt(nx * nx + ny * ny + nz * nz)
    l = np.asarray(light, dtype=float)
    l /= np.linalg.norm(l)
    return np.clip((nx * l[0] + ny * l[1] + nz * l[2]) / n, 0.0, 1.0)


def tile_window(periodic: np.ndarray, h: int, w: int, oy: int, ox: int) -> np.ndarray:
    """Sample a periodic texture into an h x w canvas so that canvas[oy, ox] == periodic[0, 0].

    Used for nine-slice sprites: the repeated centre/edge strips stay seamless.
    """
    ph, pw = periodic.shape[:2]
    ys = (np.arange(h) - oy) % ph
    xs = (np.arange(w) - ox) % pw
    return periodic[np.ix_(ys, xs)]


# ----------------------------------------------------------------------------- output

def to_u8(a: np.ndarray) -> np.ndarray:
    return np.clip(np.rint(a), 0, 255).astype(np.uint8)


def save_png(path: Path, rgb: np.ndarray, alpha: np.ndarray | None = None) -> Path:
    """Save float RGB (0..255) with optional float alpha (0..1)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if alpha is None:
        img = Image.fromarray(to_u8(rgb), "RGB")
    else:
        a = to_u8(np.clip(alpha, 0.0, 1.0) * 255.0)
        img = Image.fromarray(np.dstack([to_u8(rgb), a]), "RGBA")
    img.save(path, optimize=True)
    return path


def asset(rel: str) -> Path:
    return ASSETS / rel


def supersample_mask(draw_fn, h: int, w: int, ss: int = 4) -> np.ndarray:
    """Render a 1-bit PIL drawing at ss x resolution and box-filter it down: anti-aliased 0..1 mask."""
    from PIL import ImageDraw
    img = Image.new("L", (w * ss, h * ss), 0)
    draw_fn(ImageDraw.Draw(img), ss)
    small = img.resize((w, h), Image.Resampling.BOX)
    return np.asarray(small, dtype=float) / 255.0
