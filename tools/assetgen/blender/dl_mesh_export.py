"""Writes a Blender-built character to the game: its DLMESH1 mesh and its generated Geometry.java.

    import dl_mesh_export; dl_mesh_export.export("Mythos", "MythosGeometry", "mythos.bin", "mythos")

Needs "<Name>_Rig" (bones with model-aligned axes, as dl_rig.py / mythos_build.py make them) and "<Name>_Body" (each
triangle in one vertex group named after its bone). Each material names its texture in the custom property
"dl_texture" (a PNG in textures/entity/<texdir>/) and "dl_glow" = 1 if a "<texture>_glow.png" glows in the dark.
Vertices are written in pixels relative to their bone's pivot, at the rest pose. One Blender unit is one block,
z up, front -Y (model: y down, front -Z).
"""
import os
import struct

import bpy

ROOT = os.environ.get("DEADLANDS_ROOT") or os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))


def lp(path):
    path = os.path.abspath(path)
    prefix = "\\\\?\\"
    return prefix + path if os.name == "nt" and not path.startswith(prefix) else path


def model_px(p):
    return (p[0] * 16.0, 24.0 - p[2] * 16.0, p[1] * 16.0)


def export(name, java_class, binname, texdir):
    rig = bpy.data.objects[f"{name}_Rig"]
    body = bpy.data.objects[f"{name}_Body"]
    bones = [b.name for b in rig.data.bones]
    parents = [b.parent.name if b.parent else "root" for b in rig.data.bones]
    pivot = {b.name: model_px(b.head_local) for b in rig.data.bones}
    pivot["root"] = (0.0, 24.0, 0.0)
    me = body.data
    group_name = {g.index: g.name for g in body.vertex_groups}
    uv = me.uv_layers.active.data
    mats = [m.get("dl_texture", m.name) for m in me.materials]
    glows = [bool(m.get("dl_glow", 0)) for m in me.materials]
    groups = {}
    for poly in me.polygons:
        v0 = me.vertices[me.loops[poly.loop_indices[0]].vertex_index]
        bone = group_name[v0.groups[0].group]
        n = poly.normal
        nx, ny, nz = n.x, -n.z, n.y
        rows = groups.setdefault((bones.index(bone), poly.material_index), [])
        q = pivot[bone]
        for li in poly.loop_indices:
            p = model_px(me.vertices[me.loops[li].vertex_index].co)
            u, v = uv[li].uv
            rows.extend((p[0] - q[0], p[1] - q[1], p[2] - q[2], u, 1.0 - v, nx, ny, nz))
    out = bytearray(b"DLMESH1\0")
    out += struct.pack(">i", len(mats))
    for m, g in zip(mats, glows):
        e = m.encode("utf-8")
        out += struct.pack(">h", len(e)) + e + struct.pack(">?", g)
    out += struct.pack(">i", len(groups))
    for (bi, mi), rows in groups.items():
        out += struct.pack(">hhi", bi, mi, len(rows) // 24)
        out += struct.pack(">%df" % len(rows), *rows)
    path = os.path.join(ROOT, "src", "main", "resources", "assets", "deadlands", "models", "entity", binname)
    with open(lp(path), "wb") as fh:
        fh.write(out)

    layer = binname.rsplit(".", 1)[0]
    lines = ["package com.deadlands.client.render;", "",
             "import com.deadlands.Deadlands;",
             "import net.minecraft.client.model.geom.ModelLayerLocation;",
             "import net.minecraft.client.model.geom.PartPose;",
             "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
             "import net.minecraft.client.model.geom.builders.LayerDefinition;",
             "import net.minecraft.client.model.geom.builders.MeshDefinition;",
             "import net.minecraft.client.model.geom.builders.PartDefinition;", "",
             "/**",
             " * GENERATED by tools/assetgen/blender/dl_mesh_export.py from art/blender - do not edit; change the rig in Blender",
             " * and export again.",
             " *",
             f" * <p>{name}'s rig: pivots at the model's joints, no boxes ({{@code RiggedMesh.Layer}} draws the mesh).",
             " */",
             f"public final class {java_class} {{",
             f'\tpublic static final ModelLayerLocation LAYER = new ModelLayerLocation(Deadlands.id("{layer}"), "main");',
             "\tpublic static final String[] BONES = {" + ", ".join(f'"{b}"' for b in bones) + "};",
             "\tpublic static final String[] PARENTS = {" + ", ".join(f'"{p}"' for p in parents) + "};", "",
             f"\tprivate {java_class}() {{", "\t}", "",
             "\tpublic static LayerDefinition create() {",
             "\t\tMeshDefinition mesh = new MeshDefinition();",
             '\t\tPartDefinition root = mesh.getRoot().addOrReplaceChild("root", CubeListBuilder.create(), PartPose.offset(0.0F, 24.0F, 0.0F));']
    for b, p in zip(bones, parents):
        a, c = pivot[b], pivot[p]
        lines.append(f'\t\tPartDefinition {b} = {p}.addOrReplaceChild("{b}", CubeListBuilder.create(), '
                     f"PartPose.offset({a[0] - c[0]:.3f}F, {a[1] - c[1]:.3f}F, {a[2] - c[2]:.3f}F));")
    lines += ["\t\treturn LayerDefinition.create(mesh, 16, 16);", "\t}", "}", ""]
    java = os.path.join(ROOT, "src", "client", "java", "com", "deadlands", "client", "render", java_class + ".java")
    with open(lp(java), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    tris = sum(len(r) // 24 for r in groups.values())
    return {"bin": binname, "bytes": len(out), "tris": tris, "groups": len(groups), "java": java_class, "materials": mats}
